-- DCS: creacion completa de tablas en un ambiente vacio (prod).
-- Escrito a partir de los modelos EF (Models/ModelosListas.cs), no exportado de test:
-- los tipos/longitudes son los que el codigo necesita, pueden diferir de las tablas de test.
-- Ejecutar como UNIS_INTERFACES o un DBA (todo va calificado con el schema).

-- ===== Secuencias =====
CREATE SEQUENCE UNIS_INTERFACES.SEQ_DCS_DEPARTAMENTO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE UNIS_INTERFACES.SEQ_DCS_CATEGORIA    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE UNIS_INTERFACES.SEQ_DCS_TIPO_SOLICITUD START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE UNIS_INTERFACES.SEQ_DCS_SOLICITUD    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE UNIS_INTERFACES.SEQ_DCS_PARAMETRO    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE UNIS_INTERFACES.SEQ_DCS_LOG          START WITH 1 INCREMENT BY 1 NOCACHE;

-- ===== Tablas =====
CREATE TABLE UNIS_INTERFACES.TBL_DCS_DEPARTAMENTO (
    ID_DEPARTAMENTO     NUMBER(10)     NOT NULL,
    NOMBRE_DEPTO        VARCHAR2(200)  NOT NULL,
    CORREO_NOTIFICACION VARCHAR2(200),   -- cola interna (ServiceController)
    CORREO_EXTERNO      VARCHAR2(200),   -- cola externa (ServiceEController)
    CONSTRAINT PK_DCS_DEPARTAMENTO PRIMARY KEY (ID_DEPARTAMENTO)
);

CREATE TABLE UNIS_INTERFACES.TBL_DCS_CATEGORIA (
    ID_CATEGORIA     NUMBER(10)     NOT NULL,
    NOMBRE_CATEGORIA VARCHAR2(200)  NOT NULL,
    ID_DEPARTAMENTO  NUMBER(10)     NOT NULL,
    CONSTRAINT PK_DCS_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT FK_DCS_CATEGORIA_DEPTO FOREIGN KEY (ID_DEPARTAMENTO)
        REFERENCES UNIS_INTERFACES.TBL_DCS_DEPARTAMENTO (ID_DEPARTAMENTO)
);

CREATE TABLE UNIS_INTERFACES.TBL_DCS_TIPO_SOLICITUD (
    ID_TIPO_SOLICITUD     NUMBER(10)     NOT NULL,
    NOMBRE_TIPO_SOLICITUD VARCHAR2(200)  NOT NULL,
    ID_CATEGORIA          NUMBER(10)     NOT NULL,
    CONSTRAINT PK_DCS_TIPO_SOLICITUD PRIMARY KEY (ID_TIPO_SOLICITUD),
    CONSTRAINT FK_DCS_TIPO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES UNIS_INTERFACES.TBL_DCS_CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE UNIS_INTERFACES.TBL_DCS_SOLICITUD (
    ID_SOLICITUD      NUMBER(10)     NOT NULL,
    ID_TIPO_SOLICITUD NUMBER(10)     NOT NULL,
    EMAIL_SOLICITANTE VARCHAR2(200),
    DESCRIPCION       CLOB,            -- texto libre del formulario, sin limite en el form
    FECHA_CREACION    DATE,
    ESTADO            VARCHAR2(20),    -- PENDIENTE / ENVIADO / ERROR
    ORIGEN            VARCHAR2(50),    -- ej. SCALA; null en el flujo normal
    NUMERO_SR         VARCHAR2(30),    -- SR de Fusion vinculado; null mientras no se encuentra
    CONSTRAINT PK_DCS_SOLICITUD PRIMARY KEY (ID_SOLICITUD),
    CONSTRAINT FK_DCS_SOLICITUD_TIPO FOREIGN KEY (ID_TIPO_SOLICITUD)
        REFERENCES UNIS_INTERFACES.TBL_DCS_TIPO_SOLICITUD (ID_TIPO_SOLICITUD)
);

CREATE TABLE UNIS_INTERFACES.TBL_DCS_PARAMETRO (
    ID_PARAMETRO        NUMBER(10)     NOT NULL,
    NOMBRE_PARAMETRO    VARCHAR2(200)  NOT NULL,
    VALOR               VARCHAR2(4000),
    FECHA_ACTUALIZACION DATE,
    CONSTRAINT PK_DCS_PARAMETRO PRIMARY KEY (ID_PARAMETRO)
);

CREATE TABLE UNIS_INTERFACES.TBL_DCS_LOG (
    ID_LOG      NUMBER        NOT NULL,
    FECHA_LOG   TIMESTAMP     NOT NULL,
    NIVEL       VARCHAR2(20)  NOT NULL,
    LOGGER      VARCHAR2(200),
    MENSAJE     VARCHAR2(4000),
    EXCEPCION   VARCHAR2(4000),
    CONSTRAINT PK_DCS_LOG PRIMARY KEY (ID_LOG)
);

-- ===== Triggers de ID =====
-- TBL_DCS_SOLICITUD lo necesita: EF lee el ID generado y el codigo lo pone en el asunto ([DCS-<id>]).
CREATE OR REPLACE TRIGGER UNIS_INTERFACES.TRG_DCS_DEPARTAMENTO_BI
BEFORE INSERT ON UNIS_INTERFACES.TBL_DCS_DEPARTAMENTO FOR EACH ROW
BEGIN
    IF :NEW.ID_DEPARTAMENTO IS NULL THEN
        SELECT UNIS_INTERFACES.SEQ_DCS_DEPARTAMENTO.NEXTVAL INTO :NEW.ID_DEPARTAMENTO FROM DUAL;
    END IF;
END;
/

