SELECT 'CATEGORIA sin departamento' AS PROBLEMA, c.ID_CATEGORIA AS ID
FROM UNIS_INTERFACES.TBL_DCS_CATEGORIA c
WHERE NOT EXISTS (SELECT 1 FROM UNIS_INTERFACES.TBL_DCS_DEPARTAMENTO d WHERE d.ID_DEPARTAMENTO = c.ID_DEPARTAMENTO)
